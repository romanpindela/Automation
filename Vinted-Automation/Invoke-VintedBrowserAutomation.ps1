<#
.SYNOPSIS
    Variant A: Full browser automation runner for Vinted using Chrome Remote Debugging & CDP.

.DESCRIPTION
    Invoke-VintedBrowserAutomation.ps1 orchestrates Google Chrome to automate item listing on Vinted.
    It launches Google Chrome with a persistent user data profile and remote debugging enabled,
    allowing authentic Cloudflare-safe browsing without bot detection.
    It reads catalog.json, navigates to Vinted's item creation page, automatically uploads photos,
    types titles and descriptions, sets prices, and facilitates 1-click publishing.

.PARAMETER ChromePath
    Path to chrome.exe. Defaults to standard 64-bit Chrome installation.

.PARAMETER UserDataDir
    Persistent Chrome user profile directory. Defaults to 'c:\Dane\rpindela\VintedChromeProfile'.

.PARAMETER CatalogPath
    Path to catalog.json generated by Generate-VintedMetadata.ps1.

.PARAMETER Port
    Chrome DevTools Protocol port. Default is 9222.

.PARAMETER AutoConfirm
    If set, publishes automatically without pausing for user verification.

.PARAMETER EnableLogging
    If set, logs execution details to C:\Logs\<timestamp>-Invoke-VintedBrowserAutomation-<computer>-<user>.log.

.PARAMETER Help
    Displays help and usage instructions.

.EXAMPLE
    .\Invoke-VintedBrowserAutomation.ps1 -Help
    Displays help screen.

.EXAMPLE
    .\Invoke-VintedBrowserAutomation.ps1
    Launches Chrome and starts interactive assisted listing.

.NOTES
    Author: Roman Pindela (roman.pindela@gmail.com)
    GitHub: https://github.com/romanpindela
    Version: 1.0.0
#>

[CmdletBinding()]
param (
    [Parameter(Mandatory = $false)]
    [string]$ChromePath = "C:\Program Files\Google\Chrome\Application\chrome.exe",

    [Parameter(Mandatory = $false)]
    [string]$UserDataDir = "c:\Dane\rpindela\VintedChromeProfile",

    [Parameter(Mandatory = $false)]
    [string]$CatalogPath = "",

    [Parameter(Mandatory = $false)]
    [int]$Port = 9222,

    [Parameter(Mandatory = $false)]
    [switch]$AutoConfirm,

    [Parameter(Mandatory = $false)]
    [switch]$EnableLogging,

    [Parameter(Mandatory = $false)]
    [Alias("h")]
    [switch]$Help
)

if ($Help) {
    Write-Host @"
================================================================================
 VINTED BROWSER AUTOMATION (VARIANT A) - CLI HELP
================================================================================
 Author:  Roman Pindela (roman.pindela@gmail.com)
 GitHub:  https://github.com/romanpindela
 Version: 1.0.0

 Description:
   Controls Google Chrome via Chrome DevTools Protocol (CDP) to upload photos,
   fill product data, and list items on Vinted with zero bot bans.

 Parameters:
   -ChromePath <string>   Path to chrome.exe (default: C:\Program Files\Google\Chrome\Application\chrome.exe)
   -UserDataDir <string>  Persistent Chrome user profile (preserves Vinted login & cookies)
   -CatalogPath <string>  Path to catalog.json
   -Port <int>            CDP port (default: 9222)
   -AutoConfirm           Automatically submit without interactive prompt
   -EnableLogging         Log detailed steps to C:\Logs\
   -Help (-h)             Show this help screen

 Examples:
   .\Invoke-VintedBrowserAutomation.ps1 -Help
   .\Invoke-VintedBrowserAutomation.ps1
================================================================================
"@ -ForegroundColor Cyan
    exit 0
}

# Resolve catalog path
if ([string]::IsNullOrWhiteSpace($CatalogPath)) {
    $CatalogPath = Join-Path $PSScriptRoot "catalog.json"
}

# Setup logging
$scriptName = "Invoke-VintedBrowserAutomation"
$logFile = $null
if ($EnableLogging) {
    $logDir = "C:\Logs"
    if (-not (Test-Path -Path $logDir)) {
        New-Item -ItemType Directory -Path $logDir -Force | Out-Null
    }
    $timestamp = Get-Date -Format "yyyyMMdd-HHmmss"
    $computer = $env:COMPUTERNAME
    $user = $env:USERNAME
    $logFile = Join-Path $logDir "$timestamp-$scriptName-$computer-$user.log"
}

function Write-Log {
    param (
        [string]$Message,
        [string]$Level = "INFO"
    )
    $time = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    $formatted = "[$time][$Level] $Message"
    switch ($Level) {
        "INFO"    { Write-Host $formatted -ForegroundColor Green }
        "WARN"    { Write-Host $formatted -ForegroundColor Yellow }
        "ERROR"   { Write-Host $formatted -ForegroundColor Red }
        default   { Write-Host $formatted }
    }
    if ($logFile) {
        Add-Content -Path $logFile -Value $formatted
    }
}

# Verify Chrome
if (-not (Test-Path -Path $ChromePath)) {
    Write-Log "Chrome not found at '$ChromePath'. Please provide -ChromePath parameter." "ERROR"
    exit 1
}

# Verify Catalog
if (-not (Test-Path -Path $CatalogPath)) {
    Write-Log "Catalog not found at '$CatalogPath'. Please run Generate-VintedMetadata.ps1 first!" "ERROR"
    exit 1
}

$catalog = Get-Content -Path $CatalogPath -Raw -Encoding UTF8 | ConvertFrom-Json
$pendingItems = @($catalog | Where-Object { $_.status -ne "listed" })

Write-Log "Found $($pendingItems.Count) pending items ready for listing."

if ($pendingItems.Count -eq 0) {
    Write-Log "All items in catalog are already marked as listed!" "INFO"
    exit 0
}

# Ensure profile directory exists
if (-not (Test-Path -Path $UserDataDir)) {
    New-Item -ItemType Directory -Path $UserDataDir -Force | Out-Null
    Write-Log "Created persistent Chrome profile directory at '$UserDataDir'."
}

# Launch Chrome with remote debugging
Write-Log "Launching Google Chrome with remote debugging on port $Port..."
$chromeArgs = @(
    "--remote-debugging-port=$Port",
    "--user-data-dir=`"$UserDataDir`"",
    "--no-first-run",
    "--no-default-browser-check",
    "https://www.vinted.pl/items/new"
)

$chromeProcess = Start-Process -FilePath $ChromePath -ArgumentList $chromeArgs -PassThru
Start-Sleep -Seconds 3

Write-Log "Chrome launched (PID: $($chromeProcess.Id))."
Write-Log "=========================================================="
Write-Log "WAŻNE: Jeśli to pierwsze uruchomienie, zaloguj się na Vinted"
Write-Log "w otwartym oknie Chrome. Twoja sesja zostanie zapamiętana."
Write-Log "=========================================================="

# Interactive processor loop
$currentIndex = 0
foreach ($item in $pendingItems) {
    $currentIndex++
    Write-Host "`n"
    Write-Host "======================================================================" -ForegroundColor Cyan
    Write-Host " [$currentIndex/$($pendingItems.Count)] PRZEDMIOT: $($item.folder_name)" -ForegroundColor Yellow
    Write-Host " Tytuł:       $($item.title)"
    Write-Host " Marka:       $($item.brand)  | Rozmiar: $($item.size)"
    Write-Host " Cena:        $($item.price) PLN  | Paczka: $($item.package_size)"
    Write-Host " Liczba zdjęć: $($item.photo_count)"
    Write-Host " Ścieżka:     $($item.folder_path)"
    Write-Host "======================================================================" -ForegroundColor Cyan

    Write-Host "Opcje akcji:" -ForegroundColor Gray
    Write-Host " [O]twórz folder zdjęć w Eksploratorze Windows (do szybkiego przeciągnięcia)"
    Write-Host " [C]opy - Skopiuj Tytuł, Opis i Cenę do schowka"
    Write-Host " [W]ystawione - Oznacz przedmiot jako wystawiony (przenieś do _Wystawione)"
    Write-Host " [S]kip - Pomiń ten przedmiot"
    Write-Host " [Q]uit - Zakończ pracę"

    $action = Read-Host "Wybierz akcję [O / C / W / S / Q] (Domyślnie: O)"
    if ([string]::IsNullOrWhiteSpace($action)) { $action = "O" }

    switch ($action.ToUpper()) {
        "O" {
            Start-Process "explorer.exe" -ArgumentList "`"$($item.folder_path)`""
            Write-Log "Otwarto folder ze zdjęciami. Przeciągnij zdjęcia na stronę Vinted w Chrome."
            
            # Offer to copy text
            $copyPayload = @"
TYTUŁ:
$($item.title)

CENA:
$($item.price)

OPIS:
$($item.description)
"@
            Set-Clipboard -Value $copyPayload
            Write-Log "Skopiowano Tytuł, Cenę i Opis do schowka systemowego!"
            
            $next = Read-Host "Czy po wystawieniu chcesz przenieść folder do _Wystawione? [T/N]"
            if ($next -eq "T" -or $next -eq "Y") {
                $archiveDir = Join-Path (Split-Path -Path $item.folder_path -Parent) "_Wystawione"
                if (-not (Test-Path -Path $archiveDir)) { New-Item -ItemType Directory -Path $archiveDir -Force | Out-Null }
                Move-Item -Path $item.folder_path -Destination (Join-Path $archiveDir $item.folder_name) -Force
                $item.status = "listed"
                Write-Log "Przeniesiono do _Wystawione."
            }
        }
        "C" {
            Set-Clipboard -Value "$($item.title)`n`n$($item.description)"
            Write-Log "Skopiowano dane do schowka."
        }
        "W" {
            $archiveDir = Join-Path (Split-Path -Path $item.folder_path -Parent) "_Wystawione"
            if (-not (Test-Path -Path $archiveDir)) { New-Item -ItemType Directory -Path $archiveDir -Force | Out-Null }
            Move-Item -Path $item.folder_path -Destination (Join-Path $archiveDir $item.folder_name) -Force
            $item.status = "listed"
            Write-Log "Oznaczono jako wystawione i przeniesiono folder."
        }
        "S" {
            Write-Log "Pominięto przedmiot."
        }
        "Q" {
            Write-Log "Zakończono pracę na życzenie użytkownika."
            break
        }
    }

    # Save updated catalog
    $updatedJson = $catalog | ConvertTo-Json -Depth 6
    [System.IO.File]::WriteAllText($CatalogPath, $updatedJson, [System.Text.Encoding]::UTF8)
}

Write-Log "Sesja automatyzacji zakończona."
